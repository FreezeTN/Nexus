/**
 * Returns an official monster artwork portrait URL.
 * Checks the exact map first, then fuzzy matches, then constructs an Open5e official SRD illustration slug.
 */
export function getMonsterPortraitUrl(monsterName: string, _id?: string): string {
  if (!monsterName) {
    return 'https://www.dndbeyond.com/avatars/thumbnails/47138/568/1000/1000/638741963706659115.png';
  }

  const trimmed = monsterName.trim();

  // 1. Exact map match
  if (MONSTER_PORTRAITS_MAP[trimmed]) {
    return MONSTER_PORTRAITS_MAP[trimmed];
  }

  // 2. Partial key match
  for (const [key, url] of Object.entries(MONSTER_PORTRAITS_MAP)) {
    if (trimmed.toLowerCase().includes(key.toLowerCase())) {
      return url;
    }
  }

  // 3. Clean slug for Open5e SRD illustrations
  const cleanSlug = trimmed
    .toLowerCase()
    .replace(/\(.*?\)/g, '') // remove parenthetical notes like (3.5e)
    .trim()
    .replace(/[^a-z0-9\s-]/g, '')
    .replace(/\s+/g, '-');

  if (cleanSlug) {
    return `https://api.open5e.com/static/img/object_illustrations/open5e-illustrations/monsters/${cleanSlug}.png`;
  }

  return 'https://www.dndbeyond.com/avatars/thumbnails/47138/568/1000/1000/638741963706659115.png';
}

